  function t(value, language = currentLanguage) {
    if (value == null) return '';
    const source = String(value);
    const entry = lookup.get(source);
    if (entry) return entry[language];
    return translateDynamic(source, language);
  }

  function translateTextNode(node) {
    if (!node || !node.parentElement) return;
    if (node.parentElement.closest('script, style, [data-no-i18n]')) return;
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    const source = originalText.get(node);
    const match = source.match(/^(\s*)([\s\S]*?)(\s*)$/);
    if (!match || !match[2]) return;
    const translated = t(match[2], currentLanguage);
    const nextValue = match[1] + translated + match[3];
    if (node.nodeValue !== nextValue) node.nodeValue = nextValue;
  }

  function translateElementAttributes(element) {
    if (!(element instanceof Element) || element.closest('[data-no-i18n]')) return;
    const attributes = ['placeholder', 'title', 'aria-label'];
    let originals = originalAttributes.get(element);
    if (!originals) {
      originals = {};
      originalAttributes.set(element, originals);
    }
    attributes.forEach(name => {
      if (!element.hasAttribute(name)) return;
      if (!(name in originals)) originals[name] = element.getAttribute(name);
      const translated = t(originals[name], currentLanguage);
      if (element.getAttribute(name) !== translated) element.setAttribute(name, translated);
    });
  }

  function translateTree(root) {
    if (!root) return;
    if (root.nodeType === Node.TEXT_NODE) {
      translateTextNode(root);
      return;
    }
    if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return;
    if (root.nodeType === Node.ELEMENT_NODE) translateElementAttributes(root);
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
    let node = walker.nextNode();
    while (node) {
      if (node.nodeType === Node.TEXT_NODE) translateTextNode(node);
      else translateElementAttributes(node);
      node = walker.nextNode();
    }
  }

  function setLanguage(language) {
    currentLanguage = language === 'en' ? 'en' : 'de';
    document.documentElement.lang = currentLanguage;
    translateTree(document.body);
    document.title = t(document.title, currentLanguage);
    document.dispatchEvent(new CustomEvent('radimo:languagechange', { detail: { language: currentLanguage } }));
  }

  function initialize() {
    setLanguage(DEFAULT_LANGUAGE);
    observer = new MutationObserver(records => {
      records.forEach(record => {
        record.addedNodes.forEach(translateTree);
        if (record.type === 'attributes') translateElementAttributes(record.target);
      });
    });
    observer.observe(document.body, { childList: true, subtree: true, attributes: true, attributeFilter: ['placeholder', 'title', 'aria-label'] });
  }

  window.RadimoI18n = {
    get language() { return currentLanguage; },
    setLanguage,
    t,
    translate: translateTree
  };

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', initialize);
  else initialize();
